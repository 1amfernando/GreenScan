-- 4a. Diagnose-Timeline für eine Pflanze (own-only, INVOKER)
CREATE OR REPLACE FUNCTION public.fn_plant_diagnoses_for_plant(p_plant_id text)
  RETURNS TABLE(id uuid, diagnosed_at timestamptz, photo_url text, species_name text,
                ai_diagnosis jsonb, treatment_plan jsonb, status text,
                followup_at timestamptz, followup_result text, treatment_steps_count integer)
  LANGUAGE sql STABLE SET search_path TO 'public'
AS $function$
  SELECT d.id, d.created_at, d.photo_url, d.species_name, d.ai_diagnosis, d.treatment_plan,
    d.status, d.followup_at, d.followup_result,
    (SELECT count(*)::int FROM public.plant_treatment_steps t WHERE t.diagnosis_id = d.id)
  FROM public.plant_doctor_history d
  WHERE d.user_id = (SELECT auth.uid()) AND d.plant_local_id = p_plant_id
  ORDER BY d.created_at DESC;
$function$;

-- 4b. Fällige Follow-ups (own-only, INVOKER)
CREATE OR REPLACE FUNCTION public.fn_followup_due()
  RETURNS TABLE(id uuid, plant_id text, plant_name text, diagnosis_top text,
                diagnosed_at timestamptz, days_overdue integer)
  LANGUAGE sql STABLE SET search_path TO 'public'
AS $function$
  SELECT d.id, d.plant_local_id,
    COALESCE(NULLIF(d.species_name,''), d.ai_diagnosis->>'top', 'Pflanze'),
    d.ai_diagnosis->>'top',
    d.created_at,
    GREATEST(0, EXTRACT(day FROM now() - d.followup_due_at)::int)
  FROM public.plant_doctor_history d
  WHERE d.user_id = (SELECT auth.uid())
    AND d.status IN ('open','treating')
    AND d.followup_at IS NULL
    AND d.followup_due_at IS NOT NULL
    AND d.followup_due_at <= now()
  ORDER BY d.followup_due_at ASC;
$function$;

-- 4c. Follow-up absenden (DEFINER; mapped better→resolved / worse→worsened / else→treating)
CREATE OR REPLACE FUNCTION public.fn_followup_submit(p_diagnosis_id uuid, p_result text,
                                                     p_notes text DEFAULT NULL,
                                                     p_new_photo_url text DEFAULT NULL)
  RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
DECLARE v_uid uuid := (SELECT auth.uid()); v_new_status text;
BEGIN
  IF v_uid IS NULL THEN RETURN false; END IF;
  IF p_result NOT IN ('better','same','worse','unknown') THEN RETURN false; END IF;
  v_new_status := CASE p_result WHEN 'better' THEN 'resolved' WHEN 'worse' THEN 'worsened' ELSE 'treating' END;
  UPDATE public.plant_doctor_history
    SET followup_at = now(), followup_result = p_result, status = v_new_status, updated_at = now()
    WHERE id = p_diagnosis_id AND user_id = v_uid;
  IF NOT FOUND THEN RETURN false; END IF;
  IF p_notes IS NOT NULL OR p_new_photo_url IS NOT NULL THEN
    INSERT INTO public.plant_treatment_steps (diagnosis_id, user_id, step_label, photo_url, notes)
    VALUES (p_diagnosis_id, v_uid, 'Follow-up: ' || p_result, p_new_photo_url, p_notes);
  END IF;
  RETURN true;
END $function$;

-- 4d. Behandlungs-Schritt hinzufügen (DEFINER; ownership-check, status open→treating)
CREATE OR REPLACE FUNCTION public.fn_treatment_step_add(p_diagnosis_id uuid, p_step_label text,
                                                        p_photo_url text DEFAULT NULL,
                                                        p_notes text DEFAULT NULL)
  RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
DECLARE v_uid uuid := (SELECT auth.uid()); v_new_id bigint;
BEGIN
  IF v_uid IS NULL OR p_step_label IS NULL OR length(trim(p_step_label)) = 0 THEN RETURN NULL; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.plant_doctor_history WHERE id = p_diagnosis_id AND user_id = v_uid) THEN RETURN NULL; END IF;
  INSERT INTO public.plant_treatment_steps (diagnosis_id, user_id, step_label, photo_url, notes)
  VALUES (p_diagnosis_id, v_uid, left(p_step_label, 200), p_photo_url, p_notes)
  RETURNING id INTO v_new_id;
  UPDATE public.plant_doctor_history SET status = 'treating', updated_at = now()
    WHERE id = p_diagnosis_id AND user_id = v_uid AND status = 'open';
  RETURN v_new_id;
END $function$;

-- 4e. Behandlungs-Schritte einer Diagnose (own-only, INVOKER)
CREATE OR REPLACE FUNCTION public.fn_treatment_steps_for_diagnosis(p_diagnosis_id uuid)
  RETURNS TABLE(id bigint, step_label text, done_at timestamptz, photo_url text, notes text)
  LANGUAGE sql STABLE SET search_path TO 'public'
AS $function$
  SELECT t.id, t.step_label, t.done_at, t.photo_url, t.notes
  FROM public.plant_treatment_steps t
  WHERE t.user_id = (SELECT auth.uid()) AND t.diagnosis_id = p_diagnosis_id
  ORDER BY t.done_at ASC;
$function$;

