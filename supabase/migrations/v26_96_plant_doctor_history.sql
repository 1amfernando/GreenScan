-- ── 1. Extend plant_doctor_history (additive) ────────────────────────────────
ALTER TABLE public.plant_doctor_history
  ADD COLUMN IF NOT EXISTS species_name     text,
  ADD COLUMN IF NOT EXISTS status           text NOT NULL DEFAULT 'open',
  ADD COLUMN IF NOT EXISTS followup_due_at  timestamptz,
  ADD COLUMN IF NOT EXISTS followup_result  text,
  ADD COLUMN IF NOT EXISTS updated_at       timestamptz NOT NULL DEFAULT now();

-- CHECK constraints via DO-block (idempotent)
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'pdh_status_chk') THEN
    ALTER TABLE public.plant_doctor_history
      ADD CONSTRAINT pdh_status_chk
      CHECK (status IN ('open','treating','resolved','worsened','abandoned'));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'pdh_followup_result_chk') THEN
    ALTER TABLE public.plant_doctor_history
      ADD CONSTRAINT pdh_followup_result_chk
      CHECK (followup_result IS NULL OR followup_result IN ('better','same','worse','unknown'));
  END IF;
END $$;

