  user_id      uuid NOT NULL,
  step_label   text NOT NULL,
  done_at      timestamptz NOT NULL DEFAULT now(),
  photo_url    text,
  notes        text
);

CREATE INDEX IF NOT EXISTS idx_pts_diagnosis ON public.plant_treatment_steps (diagnosis_id);

ALTER TABLE public.plant_treatment_steps ENABLE ROW LEVEL SECURITY;

